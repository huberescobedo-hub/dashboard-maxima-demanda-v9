export function parseCoesOfficialCsv(): RawCoesRecord[] {
  const lines = COES_OFFICIAL_RAW_CSV.trim().split('\n');
  const records: RawCoesRecord[] = [];

  // Skip header: Año;Mes;Periodo;Fecha;Hora;PER-ECU Exportación MW;ECU-PER Importación MW;SEIN MW
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    const parts = line.split(';');
    if (parts.length < 8) continue;

    const year = parseInt(parts[0], 10);
    const month = parseInt(parts[1], 10);
    const period = parts[2];
    const dateRaw = parts[3]; // "29/01/2010"
    const time = parts[4]; // "19:45"
    let exportEcuMW = parseFloat(parts[5].replace(',', '.')) || 0;
    let importEcuMW = parseFloat(parts[6].replace(',', '.')) || 0;
    // Normalize if expressed in kW (international tie line PER-ECU is 220 kV with ~100 MW capacity)
    if (exportEcuMW > 500) exportEcuMW = Math.round((exportEcuMW / 1000) * 1000) / 1000;
    if (importEcuMW > 500) importEcuMW = Math.round((importEcuMW / 1000) * 1000) / 1000;
    const nationalMW = parseFloat(parts[7].replace(',', '.')) || 0;

    const [dayStr, monthStr, yearStr] = dateRaw.split('/');
    const day = parseInt(dayStr, 10);
    const dateFormatted = `${yearStr}-${monthStr.padStart(2, '0')}-${dayStr.padStart(2, '0')}`;

    const isPending = nationalMW <= 0 || time === '00:00';

    // Generate contextual note
    let note = `Máxima demanda mensual registrada por el COES: ${nationalMW.toLocaleString('es-PE', { minimumFractionDigits: 2, maximumFractionDigits: 3 })} MW el ${dateRaw} a las ${time} h.`;
    if (year === 2026 && month === 9) {
      note = `¡RÉCORD HISTÓRICO ABSOLUTO DEL SEIN!: ${nationalMW.toLocaleString('es-PE', { minimumFractionDigits: 3, maximumFractionDigits: 3 })} MW el 15/09/2026 a las 19:00 h según reporte oficial coincidente COES.`;
    } else if (year === 2026 && month === 2) {
      note = `Máxima demanda histórica previa del SEIN: ${nationalMW.toLocaleString('es-PE', { minimumFractionDigits: 2, maximumFractionDigits: 3 })} MW el 25/02/2026 a las 19:00 h según reporte oficial COES.`;
    } else if (isPending) {
      note = `Mes en curso: El COES consolida oficialmente la máxima demanda mensual tras el cierre de fin de mes.`;
    }

    records.push({
      year,
      month,
      period,
      day,
      date: dateFormatted,
      time,
      exportEcuMW,
      importEcuMW,
      nationalMW,
      notes: note,
      isOfficialCoesVerified: true,
      isPendingMonth: isPending,
    });
  }

  return records;
}
